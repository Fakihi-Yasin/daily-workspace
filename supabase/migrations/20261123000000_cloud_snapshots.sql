-- Daily Workspace — cloud sync, migration 1.
--
-- One row per (signed-in user, slot) holding the dashboard snapshot (the same compact format the
-- browser already keeps in localStorage). Identity comes from Auth0 through Supabase
-- Third-Party Auth: the Auth0 user id is the JWT `sub` claim, e.g. 'auth0|64f…'.
--
-- Access model
--   * anon (signed-out visitors, publishable key only): no privileges at all.
--   * authenticated (valid Auth0 token with role=authenticated): only rows whose
--     user_id equals their own `sub`, enforced by RLS.
--   * Writes go through save_snapshot(), an optimistic compare-and-swap so one device can never
--     silently overwrite a newer version written by another device.

begin;

create table public.snapshots (
  user_id     text        not null default (auth.jwt() ->> 'sub'),
  slot        text        not null default 'real',
  rev         text        not null,
  snapshot    jsonb       not null,
  version     bigint      not null default 1,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  primary key (user_id, slot),
  constraint snapshots_user_id_present check (length(user_id) between 3 and 255),
  constraint snapshots_slot_valid      check (slot in ('real')),
  constraint snapshots_rev_valid       check (length(rev) between 6 and 100),
  constraint snapshots_format          check (snapshot ->> 'format' = 'dashboard-snapshot'),
  constraint snapshots_size            check (pg_column_size(snapshot) < 20 * 1024 * 1024)
);

comment on table public.snapshots is 'Daily Workspace: one dashboard snapshot per Auth0 user (JWT sub) and slot. RLS: owner only.';

-- Explicit privileges: nothing for signed-out visitors, table access only for signed-in users.
revoke all on table public.snapshots from public, anon, authenticated;
grant select, insert, update, delete on table public.snapshots to authenticated;

alter table public.snapshots enable row level security;
alter table public.snapshots force row level security;

create policy snapshots_select_own on public.snapshots
  for select to authenticated
  using (user_id = (select auth.jwt() ->> 'sub'));

create policy snapshots_insert_own on public.snapshots
  for insert to authenticated
  with check (user_id = (select auth.jwt() ->> 'sub'));

create policy snapshots_update_own on public.snapshots
  for update to authenticated
  using (user_id = (select auth.jwt() ->> 'sub'))
  with check (user_id = (select auth.jwt() ->> 'sub'));

create policy snapshots_delete_own on public.snapshots
  for delete to authenticated
  using (user_id = (select auth.jwt() ->> 'sub'));

-- Compare-and-swap save. SECURITY INVOKER: runs with the caller's privileges, so the RLS policies
-- above still apply. The owner is always taken from the token, never from a parameter.
--   p_expected_rev: the cloud revision this device last synced (null = "no cloud row yet").
--   p_new_rev:      a revision id generated by the client; sending the same one again (a retry after
--                   a lost response) is recognised and succeeds without writing twice.
create function public.save_snapshot(p_slot text, p_expected_rev text, p_new_rev text, p_snapshot jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  uid text := auth.jwt() ->> 'sub';
  cur text;
begin
  if uid is null or uid = '' then
    raise exception 'not signed in' using errcode = '42501';
  end if;

  select s.rev into cur from public.snapshots s where s.user_id = uid and s.slot = p_slot for update;

  if not found then
    if p_expected_rev is not null then
      return jsonb_build_object('status', 'conflict', 'rev', null);
    end if;
    insert into public.snapshots (user_id, slot, rev, snapshot)
      values (uid, p_slot, p_new_rev, p_snapshot)
      on conflict (user_id, slot) do nothing;
    if found then
      return jsonb_build_object('status', 'ok', 'rev', p_new_rev);
    end if;
    select s.rev into cur from public.snapshots s where s.user_id = uid and s.slot = p_slot;
  end if;

  if cur = p_new_rev then
    return jsonb_build_object('status', 'ok', 'rev', cur); -- retry of a save that already landed
  end if;
  if cur is distinct from p_expected_rev then
    return jsonb_build_object('status', 'conflict', 'rev', cur);
  end if;

  update public.snapshots s
     set rev = p_new_rev, snapshot = p_snapshot, version = s.version + 1, updated_at = now()
   where s.user_id = uid and s.slot = p_slot;
  return jsonb_build_object('status', 'ok', 'rev', p_new_rev);
end;
$$;

revoke all on function public.save_snapshot(text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.save_snapshot(text, text, text, jsonb) to authenticated;

commit;
